/**
 * Translation helper function with automatic English fallback and param interpolation.
 */
export function getTranslation(
  key: TranslationKey,
  langCode: string = 'en',
  params?: Record<string, string>
): string {
  const code = (langCode || 'en').toLowerCase().split('-')[0];
  const langDict = translations[code];
  let text = langDict?.[key] || translations['en']?.[key] || key;

  if (params) {
    Object.entries(params).forEach(([paramKey, paramVal]) => {
      text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), paramVal);
    });
  }

  return text;
}
